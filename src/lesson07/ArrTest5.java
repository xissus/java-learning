package lesson07;

/**
 * lesson07：求数组最大值——课堂上跟着老师敲的第一道数组综合题。
 * <p>
 * 思路：先认定第 0 个元素最大（{@code max = arr[0]}），
 * 再拿后面每个元素跟 max 比，谁大就把谁记下来，循环结束后 max 就是最大值。
 * <p>
 * <b>为什么不能写成 {@code max = 0}？</b>如果数组里全是负数，0 会比它们都大，结果就错了。
 * 所以初值一定要取数组里的某个真实元素。
 * <p>
 * 扩展练习（还没做）：把这个程序改写成求最小值。
 * <p>
 * 运行结果：{@code 55}
 *
 * @author 杨训杰
 */
public class ArrTest5 {

	public static void main(String[] args) {
		// 定义数组求最大值：33，5，22，44，55
		//扩展问题：
		//1、根据求最大值，改写求最小值
        //2、为什么max记录为arr[0],默认值不可以为0吗
		//一定要为数组里的值
		
		
				
		// 1、定义数组用来存储5个值
		int[] arr = { 33, 5, 22, 44, 55 };// 已知5个值，选择静态初始化
		// 2、定义变量max，存储最大值
		// 临时认为0索引是最大的
		int max = arr[0];
		// 3、循环获取数组中的每一个元素
		// 拿着每一个元素跟max比较
		for (int i = 0; i < arr.length; i++) {//循环遍历
			// i索引 arr[i]元素
			if (arr[i] > max) {
				max = arr[i];
//4、当循环结束后，max即为数组最大值

			}

		}
		System.out.println(max);//55
		
		
		
		//最小值
		
	}

}
