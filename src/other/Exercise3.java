package other;

/**
 * other：平方和（数组版）——把 1~500 里所有能被 7 整除的数挑出来，求它们的平方和。
 * <p>
 * <b>题目：</b>用循环结构，计算 1~500 中能被 7 整除的所有数的平方和。
 * <p>
 * <b>思路分两步走：</b>
 * <ol>
 * <li>先按顺序把 1~500 这 500 个数<b>装进一个数组</b>，让它们待在内存里；</li>
 * <li>再从头到尾扫一遍数组，谁的 {@code % 7 == 0}（除以 7 余 0，也就是能被 7 整除）， 就把它的平方加进 {@code sum}
 * 里。</li>
 * </ol>
 * <p>
 * <b>下标从 0 开始的坑：</b>数组的下标是 {@code 0, 1, 2, …}，第一个格子叫 {@code arr[0]}。 我们要的是从 1
 * 开始的数，所以存的时候写 {@code arr[i] = i + 1} —— 把「下标」翻译成「真正想要的数」。这一步千万别漏，漏了整道题都会差 1。
 * <p>
 * <b>为什么要先装进数组？</b>因为这道题一共写了两个版本——这个「数组版」， 和同包的 {@code Exercise4}「for
 * 循环版」，专门用来体会两者的区别： <b>数组不是必须的</b>，它解决的是「数据要留下来、以后还得再用一次」的问题。
 * 这里的每个数扫一遍就完事了，{@code Exercise4} 直接拿循环变量 {@code i} 当数用， 连数组都省掉。什么时候非用数组？想想
 * lesson06 求平均分—— 得先把 10 个成绩全读完，之后还要回头一个个去比，那时候成绩就必须留在数组里。
 * <p>
 * <b>为什么用 {@code long} 存 sum？</b>这题的答案 {@code 5969964} 其实 {@code int} 也装得下，
 * 但「平方和」这种一路加下去的数长得很快，用 {@code long} 更保险， 反正 Java 允许小转大，多花这点心思不亏。
 * <p>
 * <b>运行后你会看到：</b>
 *
 * <pre>
 * 结果为5969964
 * </pre>
 *
 * （1~500 里 7 的倍数一共 71 个，最大的是 497，下一个 504 就超过 500 了。）
 *
 * @author 杨训杰
 */
public class Exercise3 {

	public static void main(String[] args) {
		// 需求：计算 1~500 中所有「能被 7 整除」的数的平方和（数组版）

		// 第一步：造一个能装 500 个格子的数组，把 1~500 依次放进去
		int[] arr = new int[500];
		for (int i = 0; i < arr.length; i++) {
			// 下标 i 是 0、1、2…，要装的数是 1、2、3…，所以统一加 1
			arr[i] = i + 1;
		}

		// 第二步：从头扫一遍数组，挑出 7 的倍数累加平方
		long sum = 0; // 累加器，从 0 开始（记住：加法从 0 开始，乘法从 1 开始）
		for (int i = 0; i < arr.length; i++) {
			// % 是取余：arr[i] % 7 等于 0，就说明这个数能被 7 整除
			if (arr[i] % 7 == 0) {
				// 把它的平方加进累加器：arr[i] * arr[i] 就是这个数的平方
				sum = sum + arr[i] * arr[i];
			}
		}

		System.out.println("结果为" + sum);
	}

}
