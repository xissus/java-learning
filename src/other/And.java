package other;

/**
 * other：把小数结果「砍」成整数——算 45.98 + 78.12 的和，但只保留整数部分。
 * <p>
 * <b>题目：</b>编写一个程序，计算 45.98 与 78.12 的和，并要求输出结果为整数。
 * <p>
 * <b>关键就是这一行：</b>{@code int sum = (int) (a + b);}
 * <p>
 * {@code a + b} 算出来是 {@code 124.1}，是个带小数的值（{@code double}）； 而 {@code sum} 声明成了
 * {@code int}，只能装整数。想让小数塞进整数里， 就得在它前面写一个 {@code (int)} —— 这叫<b>强制类型转换</b>：
 * 等于你亲口跟 Java 说「我知道要丢点东西，我认了，让我转」。
 * <p>
 * <b>它是「砍」不是「四舍五入」：</b>{@code (int) 124.9} 得到的是 {@code 124}，不是 125。
 * 小数部分被直接扔掉，不看它是 .1 还是 .9。
 * <p>
 * <b>两个小括号别省：</b>{@code (int) (a + b)} 才是「先把 a 和 b 加起来、再砍」。 要是写成
 * {@code (int) a + b}，就变成「先把 a 砍成 45，再和 b 相加」， 得到 123.12，完全是另一个结果。
 * <p>
 * <b>两件容易搞混的事：</b>
 * <ul>
 * <li><b>大转小</b>（小数 → 整数）必须你自己写 {@code (int)}；不写编译器直接报错 「不兼容的类型：从 double 转换到
 * int 可能会有损失」—— 意思就是「这个位置装不下带小数的值」。</li>
 * <li><b>小转大</b>（整数 → 小数）Java 会自己动手，不用你管。 所以 {@code double d = 5;} 能直接通过。</li>
 * </ul>
 * 一句话背下来：<b>小 → 大，Java 自己来；大 → 小，必须你亲自动手。</b>
 * <p>
 * <b>运行后你会看到：</b>
 *
 * <pre>
 * 124
 * </pre>
 *
 * （{@code 45.98 + 78.12} 按理是 124.1，砍掉小数就剩 124。）
 * <p>
 * <b>小知识：</b>小数之间相加相乘，偶尔会带一条极小的「尾巴」 （计算机存小数存不了绝对精确），这里算出来可能是
 * {@code 124.10000000000001}。 不用担心——反正小数都要被砍掉，结果一样是 124。
 *
 * @author 杨训杰
 */
public class And {

	public static void main(String[] args) {
		// 题目：算 45.98 + 78.12 的和，但结果要求输出成整数
		double a = 45.98;
		double b = 78.12;

		// (int) 就是强制类型转换：把右边算出来的小数，硬塞进左边的 int 里。
		// 记住它是「砍掉」小数，不是四舍五入——(int) 124.9 也得 124。
		// 两个括号别省：(int) (a + b) 是先算和再砍，
		// 写成 (int) a + b 就变成先把 a 砍成 45 再相加了，结果不对。
		int sum = (int) (a + b);

		// 输出结果：124
		System.out.println(sum);
	}

}
