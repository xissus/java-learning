package other;

/**
 * other：平方和（for 循环版）——和同包的 {@code Exercise3} 是同一道题， 但不借助数组，直接拿循环变量 {@code i}
 * 当那个数用。
 * <p>
 * <b>题目：</b>用循环结构，计算 1~500 中能被 7 整除的所有数的平方和。
 * <p>
 * <b>它和数组版的区别只有一点：</b>{@code Exercise3} 走的是「先把 1~500 装进数组，
 * 再扫数组」；这里把数组整个省掉了——{@code i} 从 1 数到 500， 当它正好是 7 的倍数时，{@code i} 本身就是我们要的那个数，
 * 直接拿来平方加进 {@code sum} 就行。
 * <p>
 * 也就是说：<b>数组不是必须的。</b>只有当数据「用完还得留着、以后再拿出来用」时， 才需要数组帮忙存着；像这里每个数看一眼就完事，留它干什么。
 * 平时写代码，能用循环直接算的，就别先绕一圈去建数组。
 * <p>
 * <b>循环条件 {@code i <= 500} 的边界要盯紧：</b>必须是「小于等于」。 要是手滑写成 {@code i < 500}，就会把 500
 * 漏掉——虽然 500 不是 7 的倍数、 对这题答案没影响，但「少跑一圈」这个毛病本身很危险， 换个题目（比如算 1~500 的总和）就直接算错了。
 * <p>
 * <b>为什么用 {@code long} 存 sum？</b>答案 {@code 5969964} 用 {@code int} 也装得下，
 * 但平方和是越加越大的，用 {@code long} 图个保险。
 * <p>
 * <b>运行后你会看到：</b>
 *
 * <pre>
 * 结果为5969964
 * </pre>
 *
 * 和 {@code Exercise3} 的输出一模一样——同一道题、两种写法，结果本来就应该一样。
 *
 * @author 杨训杰
 */
public class Exercise4 {

	public static void main(String[] args) {
		// 需求：计算 1~500 中所有「能被 7 整除」的数的平方和（for 循环版）

		// 累加器，从 0 开始（加法从 0 开始；要是累乘，就得从 1 开始）
		long sum = 0;

		// i 从 1 数到 500，注意是「小于等于」500，不能漏掉最后一个
		for (int i = 1; i <= 500; i++) {
			// % 是取余：i % 7 == 0，说明 i 能被 7 整除
			if (i % 7 == 0) {
				// i 本身就是那个数，直接平方加进去，不用先存进数组
				sum = sum + i * i;
			}
		}

		System.out.println("结果为" + sum);
	}

}
