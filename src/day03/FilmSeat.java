package day03;

import java.util.Scanner;

/**
 * day03：if 里面再套一个 if（嵌套）——先查票号合不合法，再算座位在左边还是右边。
 * <p>
 * <b>题目：</b>输入一个座位票号，判断座位在左边还是右边； 票号必须是 0~100，超出范围要给提示。
 * <p>
 * <b>这一课在练什么：</b>{@code if} 的**嵌套**——一个 {@code if} 的里面再写一个 {@code if}。
 * 为什么要套两层？因为这两件事有**先后顺序**：
 *
 * <pre>
 * 第一层：这个票号是有效的吗？（0~100）
 *    └─ 有效  → 第二层：它是奇数还是偶数？→ 决定左边 / 右边
 *    └─ 无效  → 直接提示「请输入0-100的票号」
 * </pre>
 *
 * 顺序不能颠倒。要是先判奇偶、再判范围，那 200 这种非法票号也会算出个「左边右边」来， 等于先算了一个没意义的答案再去检查 ——
 * 现实里这叫「先干活再验票」，很危险。
 * <p>
 * <b>第一层里用到了 {@code &&}：</b> {@code ticket >= 0 && ticket <= 100} 的意思是「既要大于等于
 * 0，又要小于等于 100」， 两个条件**同时成立**才算在范围内。判断一个「区间」时标准写法就是这个样子。
 * <p>
 * <b>运行后你会看到：</b>
 *
 * <pre>
 * 请输入要查询的票号
 * 座位在右边          （输入 5，5 是奇数）
 * 座位在左边          （输入 6，6 是偶数）
 * 请输入0-100的票号   （输入 200，超出范围）
 * </pre>
 * <p>
 * <b>留个问题：</b>如果输入 {@code 0} 会走哪边？ 提示：代码判的是「{@code ticket % 2 == 1}」，而
 * {@code 0 % 2} 等于 {@code 0} —— 先自己猜一个，再跑一遍验证，看看符不符合直觉。
 *
 * @author 杨训杰
 */
public class FilmSeat {

	public static void main(String[] args) {
		Scanner sc = new Scanner(System.in);
		System.out.println("请输入要查询的票号");
		int ticket = sc.nextInt();
		// 第一层：先确认票号是合法的（0~100 之间）。
		// && 表示「两个条件都要成立」——左边 >= 0、右边 <= 100，缺一个都不算在范围内。
		if (ticket >= 0 && ticket <= 100) {

			// 第二层：票号合法了，才轮到判断奇偶。
			// % 是取余，ticket % 2 等于 1 说明是奇数。奇数在右、偶数在左。
			if (ticket % 2 == 1) {
				System.out.println("座位在右边");
			} else {
				System.out.println("座位在左边");
			}
		} else {

			System.out.println("请输入0-100的票号");
		}
		sc.close();
	}

}
